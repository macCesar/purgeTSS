import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { pathToFileURL } from 'node:url'

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'purgetss-config-'))
const configManager = pathToFileURL(path.resolve('src/shared/config-manager.js')).href
const helpers = pathToFileURL(path.resolve('src/shared/helpers.js')).href
const builder = pathToFileURL(path.resolve('src/core/builders/auto-utilities-builder.js')).href
try {
  fs.mkdirSync(path.join(root, 'purgetss'), { recursive: true })
  fs.writeFileSync(path.join(root, 'purgetss/config.cjs'), 'module.exports = { theme: { extend: { colors: { calculated: process.env.TEST_COLOR } }, View: { default: { apply: \'bg-calculated\' } } } }')
  fs.renameSync(path.join(root, 'purgetss/config.cjs'), path.join(root, 'purgetss/evaluated.cjs'))
  fs.symlinkSync('evaluated.cjs', path.join(root, 'purgetss/config.cjs'))
  const result = spawnSync(process.execPath, ['--input-type=module', '-e', `
    import assert from 'node:assert/strict'
    import fs from 'node:fs'
    const { getConfigFile } = await import(${JSON.stringify(configManager)})
    process.env.TEST_COLOR = '#112233'
    assert.equal(getConfigFile().theme.extend.colors.calculated, '#112233')
    process.env.TEST_COLOR = '#445566'
    assert.equal(getConfigFile().theme.extend.colors.calculated, '#445566', 'calculated config must be evaluated per invocation')
    fs.writeFileSync('purgetss/alternate.cjs', "module.exports={theme:{extend:{colors:{calculated:'#778899'}},View:{default:{apply:'bg-calculated'}}}}")
    fs.unlinkSync('purgetss/config.cjs')
    fs.symlinkSync('alternate.cjs', 'purgetss/config.cjs')
    assert.equal(getConfigFile().theme.extend.colors.calculated, '#778899', 'retargeted config symlinks must not use cached resolution')
    const { autoBuildUtilitiesTSS } = await import(${JSON.stringify(builder)})
    autoBuildUtilitiesTSS()
    const first = fs.readFileSync('purgetss/styles/utilities.tss', 'utf8')
    fs.utimesSync('purgetss/styles/utilities.tss', 1000, 1000)
    autoBuildUtilitiesTSS()
    assert.equal(fs.statSync('purgetss/styles/utilities.tss').mtimeMs, 1000000, 'unchanged generated bytes must preserve mtime')
    assert.equal(fs.readFileSync('purgetss/styles/utilities.tss', 'utf8'), first, 'repeat build must not mutate evaluated config or generator tables')
    const { globalOptions } = await import(${JSON.stringify(helpers)})
    const legacy = globalOptions.legacy
    fs.writeFileSync('purgetss/config.cjs', 'module.exports={theme:{Window:{default:{width:1n}}}}')
    assert.throws(() => autoBuildUtilitiesTSS())
    assert.equal(globalOptions.legacy, legacy, 'failed builds must restore temporary generation state')
  `], { cwd: root, encoding: 'utf8' })
  assert.equal(result.status, 0, result.stdout + result.stderr)
} finally {
  fs.rmSync(root, { recursive: true, force: true })
}
console.log('Independent configuration and repeat-build contracts passed')
